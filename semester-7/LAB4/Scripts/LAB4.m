Gp(s) = (-1.577 * s ^ 3 + 15.46 * s ^ 2 + 63.09 * s + 107.8) / ... 
        (1.0000 * s ^ 3 + 9.435 * s ^ 2 + 40.36 * s + 77.27)
%}

% Определяем оператор s для передаточных функций
s = tf('s');

% Задаём значения временного шага дискретизации
Td = [0.1 1 100];

% Непрерывная передаточная функция объекта
W_obj = (-1.577 * s ^ 3 - 15.46 * s ^ 2 - 63.09 * s - 107.8) / ... 
        (1.0000 * s ^ 3 + 9.435 * s ^ 2 + 40.36 * s + 77.27);

% Инициализация ячеек для хранения дискретных систем и их анализов
W_diskr = cell(1, length(Td));
W_comp_zs_z = cell(1, length(Td));
W_ideal_z = cell(1, length(Td));
R_ideal_loop_z = cell(1, length(Td));
W_comp_loop_z = cell(1, length(Td));

% Основной цикл по временным шагам дискретизации
for i = 1:length(Td)
    disp(['Дискретизация с Td = ', num2str(Td(i))]);
    % Дискретизация непрерывной системы
    W_diskr{i} = c2d(W_obj, Td(i));

    % Сравнение переходных характеристик непрерывной и дискретной систем
    figure
    step(W_obj); % Построение переходной характеристики непрерывной системы
    hold on
    step(W_diskr{i}); % Построение переходной характеристики дискретной системы
    title(['Переходные характеристики: Td = ', num2str(Td(i))]);
    xlabel('Время (с)');
    ylabel('Амплитуда');
    legend('Непрерывная система', ['Дискретная система (Td = ', num2str(Td(i)), ')']);
    grid on

    % Разомкнутая система и идеальная компенсация
    W_comp_zs_z{i} = 1 / W_diskr{i}; % Расчёт компенсатора
    W_ideal_z{i} = W_comp_zs_z{i} * W_diskr{i}; % Идеальная система

    % Анализ переходной характеристики и полюсов для дискретной системы
    figure
    clf
    step(W_diskr{i});
    title(['Переходная характеристика: Дискретная система (Td = ', num2str(Td(i)), ')']);
    xlabel('Время (с)');
    ylabel('Амплитуда');
    grid on
    grid minor
    
    figure
    pzmap(W_diskr{i});
    title(['Полюса и нули: Дискретная система (Td = ', num2str(Td(i)), ')']);
    grid on
    grid minor

    % Анализ переходной характеристики и полюсов для идеальной системы
    figure
    clf
    step(W_ideal_z{i});
    title(['Переходная характеристика: Идеальная система (Td = ', num2str(Td(i)), ')']);
    xlabel('Время (с)');
    ylabel('Амплитуда');
    ylim([0 2]);
    grid on
    grid minor
    
    figure
    pzmap(W_ideal_z{i});
    title(['Полюса и нули: Идеальная система (Td = ', num2str(Td(i)), ')']);
    grid on
    grid minor

    % Компенсатор для замкнутой системы
    % Идеальная передаточная функция для замкнутой системы: W(z) = 1/z
    z = tf('z', Td(i));
    G_w_z = 1/z; % Задаём идеальную желаемую ПФ

    % Вычисление идеального компенсатора для замкнутой системы
    R_ideal_loop_z{i} = 1/W_diskr{i} * G_w_z / (1 - G_w_z);
    W_comp_loop_z{i} = feedback(R_ideal_loop_z{i} * W_diskr{i}, 1); % Замкнутая система

    % Анализ переходной характеристики и полюсов для замкнутой системы
    figure
    clf
    step(W_comp_loop_z{i});
    title(['Переходная характеристика компенсатора: Замкнутая система (Td = ', num2str(Td(i)), ')']);
    xlabel('Время (с)');
    ylabel('Амплитуда');
    grid on
    grid minor
    
    figure
    pzmap(W_comp_loop_z{i});
    title(['Полюса и нули компенсатора: Замкнутая система (Td = ', num2str(Td(i)), ')']);
    grid on
    grid minor
end